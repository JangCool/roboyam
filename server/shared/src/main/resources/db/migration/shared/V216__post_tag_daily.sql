-- 글 태그 일별 집계(docs/features/post-tags-contract.md 「집계」 — 사용자 결정 2026-11-15: 많이 달린 태그를 요청마다 세지 않고 미리 세어 둔 표 + DB 크론).
--
-- post_tag_daily: 한국 날짜(Asia/Seoul) 하루 · 게시판 · 태그(비교 열쇠)마다 그 태그가 달린 보이는 글 수.
--   day       = 글을 쓴 한국 날짜(posts.created_at 기준)
--   tag_key   = post_tags.tag_key(영문 소문자 비교 열쇠)
--   tag       = 그날 그 게시판에서 그 열쇠로 가장 많이 쓴 모양(같으면 글자 차례) — 읽는 쪽은 기간 안에서 post_count 합이 가장 큰 모양을 보인다
--   post_count = 그 태그가 달린 글 수(글당 열쇠 하나라 행 수 = 글 수)
-- 쓰는 곳은 DB 배치 하나뿐(R__batch_44_post_tag_daily.sql — 날마다 지우고 다시 넣기). 셀 글의 조건·주기는 그 파일 머리말.
-- 읽는 곳: PostTagQueries#popular(관리자 태그 추천 GET /api/admin/tags/popular · 매거진 GET /api/tips 태그 칩) — day 범위(+ 게시판 범위)로 합한다.
-- 외래 키 없음(post_tags 와 같은 이유 — 게시판을 지워도 지난 날 집계는 읽는 쪽 범위로 거른다).
CREATE TABLE post_tag_daily (
    day        date        NOT NULL,
    board_id   bigint      NOT NULL,
    tag_key    varchar(40) NOT NULL,
    tag        varchar(20) NOT NULL,
    post_count int         NOT NULL,
    CONSTRAINT pk_post_tag_daily PRIMARY KEY (day, board_id, tag_key)
);
-- 게시판 범위 + 날 범위 조회(관리자 추천 boards=… · 매거진 묶음 게시판). 전체 범위는 PK 의 day 앞부분으로 읽는다.
CREATE INDEX ix_post_tag_daily_board_day ON post_tag_daily (board_id, day);

-- post_tag_dirty_days: 태그가 실제로 바뀐 글(넣기·빼기·표기 변경 — 앱 PostTagStore#replace)의 「작성일(한국 날짜) · 게시판」 표시. 집계 배치가 그 날을 다시 세며 지운다.
--   태그를 모두 뺀 오래된 글은 post_tags 행이 없어 배치가 「바뀐 글」로 찾을 수 없다 — 이 표시로 그 날을 다시 센다.
--   앱은 넣기만 한다(일련번호 키 — 같은 날·게시판을 여러 글이 동시에 고쳐도 키가 부딪쳐 글 저장이 실패하지 않게. 같은 날 줄이 여러 개여도 배치가 그 날을 한 번 센다).
CREATE TABLE post_tag_dirty_days (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day        date        NOT NULL,
    board_id   bigint      NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE INDEX ix_post_tag_dirty_days_day ON post_tag_dirty_days (day);

