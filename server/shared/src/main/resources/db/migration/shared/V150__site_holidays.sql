--
-- 무엇이 바뀌나
--   ① site_holidays — 사이트 전체의 쉬는 날. 출처 PUBLIC_DATA(공공데이터 특일 정보에서 받음) · SEED(공식 자료로 넣은 기본값) · OPERATOR(운영자가 넣은 회사 휴무일).
--      같은 날에 여러 줄이 있을 수 있다(공휴일 둘 — 2025-05-05 어린이날·부처님오신날 — 또는 공휴일 + 회사 휴무일). 회사 휴무일은 하루에 한 줄.
--      쉬는 날 판정 = 토·일 + 이 표의 모든 날(BusinessDayCalendar). 공동구매 영업일과 로보티콘 정산 지급일이 같이 쓴다.
--   ② public_holidays(V146) → SEED 줄로 옮기고 지운다. 공공데이터에서 그 해를 처음 받으면 그 해의 SEED 줄은 지워진다(HolidaySyncService).
--   ③ 공구 설정의 holidays 칸 → OPERATOR 줄로 옮기고(넣은 운영자 없음, 이름 「공동구매 휴일(옮김)」) 칸을 지운다.
--   ④ site_holiday_sync — 공공데이터 받기의 마지막 결과(1행, 화면 표시용).
--   ⑤ public_data_endpoints — 공공데이터 API 주소 설정(국세청 사업자 상태 조회 기본 주소 · 특일 정보 주소·요청 글자 틀·응답 칸 이름). 비우면 코드의 공식 기본값.

-- ── ① 쉬는 날 ──
CREATE TABLE site_holidays (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date date         NOT NULL,
    name         varchar(40)  NOT NULL,
    source       varchar(12)  NOT NULL,
    substitute   boolean      NOT NULL DEFAULT false,
    created_by   bigint       REFERENCES operators (id) ON DELETE SET NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_site_holidays_source CHECK (source IN ('PUBLIC_DATA', 'SEED', 'OPERATOR')),
    CONSTRAINT ck_site_holidays_name CHECK (length(btrim(name)) BETWEEN 1 AND 40),
    CONSTRAINT ck_site_holidays_operator_name CHECK (source <> 'OPERATOR' OR length(btrim(name)) <= 30),
    CONSTRAINT ux_site_holidays_named UNIQUE (source, holiday_date, name)
);
-- 회사 휴무일은 하루에 한 줄
CREATE UNIQUE INDEX ux_site_holidays_operator_day ON site_holidays (holiday_date) WHERE source = 'OPERATOR';
CREATE INDEX ix_site_holidays_date ON site_holidays (holiday_date);

-- ── ② 기본값(V146 시드) 옮기기 ──
INSERT INTO site_holidays (holiday_date, name, source, substitute, created_at, updated_at)
SELECT holiday_date, name, 'SEED', kind = 'SUBSTITUTE', created_at, created_at FROM public_holidays;
DROP TABLE public_holidays;

-- ── ③ 공구 설정 휴일 옮기기 ──
INSERT INTO site_holidays (holiday_date, name, source)
SELECT DISTINCT d, '공동구매 휴일(옮김)', 'OPERATOR' FROM group_buy_settings s, unnest(s.holidays) AS d
ON CONFLICT DO NOTHING;
ALTER TABLE group_buy_settings DROP COLUMN holidays;

-- ── ④ 받기 결과 ──
-- outcome: OK 모두 반영 · PARTIAL 일부 해만 반영 · NO_KEY 인증키 없음(건너뜀) · FAILED 모두 실패(표는 그대로)
CREATE TABLE site_holiday_sync (
    id            integer      PRIMARY KEY CHECK (id = 1),
    ran_at        timestamptz  NOT NULL,
    outcome       varchar(8)   NOT NULL,
    applied_years integer[]    NOT NULL DEFAULT '{}',
    failed_years  integer[]    NOT NULL DEFAULT '{}',
    changed       integer      NOT NULL DEFAULT 0,
    ran_by        bigint       REFERENCES operators (id) ON DELETE SET NULL,
    CONSTRAINT ck_site_holiday_sync_outcome CHECK (outcome IN ('OK', 'PARTIAL', 'NO_KEY', 'FAILED'))
);

-- ── ⑤ 공공데이터 API 주소 ──
-- api: NTS 국세청 사업자 상태 조회(base_url = 기본 주소, 경로는 코드) · HOLIDAY 특일 정보 공휴일(base_url = 오퍼레이션 주소 전체).
-- 빈 칸(NULL)은 코드의 공식 기본값을 쓴다. 저장하면 다음 요청부터 쓴다(요청마다 DB 를 읽는다 — 서버가 여럿이어도 같다).
-- query_template: 요청 글자 틀({serviceKey}·{year}·{month}·{pageNo}·{numOfRows} 자리 — HOLIDAY 만) · date_field·name_field: 응답 item 의 날짜·이름 칸 이름(HOLIDAY 만).
CREATE TABLE public_data_endpoints (
    api            varchar(10)   PRIMARY KEY,
    base_url       varchar(500),
    query_template varchar(1000),
    date_field     varchar(50),
    name_field     varchar(50),
    updated_at     timestamptz,
    updated_by     bigint        REFERENCES operators (id) ON DELETE SET NULL,
    tested_result  varchar(16),
    tested_at      timestamptz,
    tested_by      bigint        REFERENCES operators (id) ON DELETE SET NULL,
    CONSTRAINT ck_public_data_endpoints_api CHECK (api IN ('NTS', 'HOLIDAY')),
    CONSTRAINT ck_public_data_endpoints_https CHECK (base_url IS NULL OR base_url LIKE 'https://%')
);
